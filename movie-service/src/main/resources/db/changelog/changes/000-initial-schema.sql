CREATE TABLE movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    duration_minutes INTEGER NOT NULL,
    release_date DATE NOT NULL,
    poster_url VARCHAR(500),
    trailer_url VARCHAR(500),
    language VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    rating_count INTEGER NOT NULL DEFAULT 0,
    average_rating DECIMAL(3, 2) NOT NULL DEFAULT 0.0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_movies PRIMARY KEY (id),
    CONSTRAINT uc_movies_uuid UNIQUE (uuid),
    CONSTRAINT chk_movies_duration CHECK (duration_minutes > 0),
    CONSTRAINT chk_movies_rating_count CHECK (rating_count >= 0),
    CONSTRAINT chk_movies_average_rating CHECK (average_rating >= 0.0 AND average_rating <= 10.0)
);

CREATE INDEX idx_movies_uuid ON movies(uuid);
CREATE INDEX idx_movies_title ON movies(title);
CREATE INDEX idx_movies_is_active ON movies(is_active);
CREATE INDEX idx_movies_release_date ON movies(release_date);
CREATE INDEX idx_movies_average_rating ON movies(average_rating);
CREATE INDEX idx_movies_language ON movies(language);

CREATE TABLE directors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    name VARCHAR(255) NOT NULL,
    biography TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_directors PRIMARY KEY (id),
    CONSTRAINT uc_directors_uuid UNIQUE (uuid),
    CONSTRAINT uc_directors_name UNIQUE (name)
);

CREATE INDEX idx_directors_uuid ON directors(uuid);
CREATE INDEX idx_directors_name ON directors(name);

CREATE TABLE stars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    name VARCHAR(255) NOT NULL,
    biography TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_stars PRIMARY KEY (id),
    CONSTRAINT uc_stars_uuid UNIQUE (uuid),
    CONSTRAINT uc_stars_name UNIQUE (name)
);

CREATE INDEX idx_stars_uuid ON stars(uuid);
CREATE INDEX idx_stars_name ON stars(name);

CREATE TABLE genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_genres PRIMARY KEY (id),
    CONSTRAINT uc_genres_uuid UNIQUE (uuid),
    CONSTRAINT uc_genres_name UNIQUE (name)
);

CREATE INDEX idx_genres_uuid ON genres(uuid);
CREATE INDEX idx_genres_name ON genres(name);

CREATE TABLE movie_genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    movie_id BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_movie_genres PRIMARY KEY (id),
    CONSTRAINT fk_movie_genres_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_genres_genre FOREIGN KEY (genre_id) REFERENCES genres (id) ON DELETE RESTRICT,
    CONSTRAINT uc_movie_genres_movie_genre UNIQUE (movie_id, genre_id)
);

CREATE INDEX idx_movie_genres_movie_id ON movie_genres(movie_id);
CREATE INDEX idx_movie_genres_genre_id ON movie_genres(genre_id);

CREATE TABLE movie_directors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    movie_id BIGINT NOT NULL,
    director_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_movie_directors PRIMARY KEY (id),
    CONSTRAINT fk_movie_directors_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_directors_director FOREIGN KEY (director_id) REFERENCES directors (id) ON DELETE RESTRICT,
    CONSTRAINT uc_movie_directors_movie_director UNIQUE (movie_id, director_id)
);

CREATE INDEX idx_movie_directors_movie_id ON movie_directors(movie_id);
CREATE INDEX idx_movie_directors_director_id ON movie_directors(director_id);

CREATE TABLE movie_stars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    movie_id BIGINT NOT NULL,
    star_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_movie_stars PRIMARY KEY (id),
    CONSTRAINT fk_movie_stars_movie FOREIGN KEY (movie_id) REFERENCES movies (id) ON DELETE CASCADE,
    CONSTRAINT fk_movie_stars_star FOREIGN KEY (star_id) REFERENCES stars (id) ON DELETE RESTRICT,
    CONSTRAINT uc_movie_stars_movie_star UNIQUE (movie_id, star_id)
);

CREATE INDEX idx_movie_stars_movie_id ON movie_stars(movie_id);
CREATE INDEX idx_movie_stars_star_id ON movie_stars(star_id);

-- Composite indexes for common queries
CREATE INDEX idx_movies_active_release ON movies(is_active, release_date DESC) WHERE is_active = TRUE;
CREATE INDEX idx_movies_rating_active ON movies(average_rating DESC, is_active) WHERE is_active = TRUE;
CREATE INDEX idx_movies_language_active ON movies(language, is_active, release_date DESC) WHERE is_active = TRUE;
