CREATE TABLE schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    movie_uuid VARCHAR(36) NOT NULL,
    cinema_hall VARCHAR(100) NOT NULL,
    show_date DATE NOT NULL,
    show_time TIME WITHOUT TIME ZONE NOT NULL,
    end_time TIME WITHOUT TIME ZONE NOT NULL,
    total_seats INTEGER NOT NULL,
    available_seats INTEGER NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_schedules PRIMARY KEY (id),
    CONSTRAINT uc_schedules_uuid UNIQUE (uuid),
    CONSTRAINT uc_schedules_hall_datetime UNIQUE (cinema_hall, show_date, show_time),
    CONSTRAINT chk_schedules_total_seats CHECK (total_seats > 0),
    CONSTRAINT chk_schedules_available_seats CHECK (available_seats >= 0 AND available_seats <= total_seats),
    CONSTRAINT chk_schedules_price CHECK (price >= 0),
    CONSTRAINT chk_schedules_end_time CHECK (end_time > show_time)
);

CREATE INDEX idx_schedules_uuid ON schedules(uuid);
CREATE INDEX idx_schedules_movie_uuid ON schedules(movie_uuid);
CREATE INDEX idx_schedules_cinema_hall ON schedules(cinema_hall);
CREATE INDEX idx_schedules_show_date ON schedules(show_date);
CREATE INDEX idx_schedules_is_active ON schedules(is_active);
CREATE INDEX idx_schedules_show_datetime ON schedules(show_date, show_time);
CREATE INDEX idx_schedules_available_seats ON schedules(available_seats);

-- Composite indexes for common queries
CREATE INDEX idx_schedules_movie_date_active ON schedules(movie_uuid, show_date, is_active) WHERE is_active = TRUE;
CREATE INDEX idx_schedules_date_hall_active ON schedules(show_date, cinema_hall, is_active) WHERE is_active = TRUE;
CREATE INDEX idx_schedules_availability ON schedules(show_date, available_seats) WHERE is_active = TRUE AND available_seats > 0;
