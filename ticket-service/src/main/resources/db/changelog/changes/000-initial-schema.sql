CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    user_uuid VARCHAR(36) NOT NULL,
    schedule_uuid VARCHAR(36) NOT NULL,
    seat_number VARCHAR(10) NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    booking_time TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_time TIMESTAMP WITHOUT TIME ZONE,
    payment_id VARCHAR(100),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_tickets PRIMARY KEY (id),
    CONSTRAINT uc_tickets_uuid UNIQUE (uuid),
    CONSTRAINT uc_tickets_schedule_seat UNIQUE (schedule_uuid, seat_number),
    CONSTRAINT chk_tickets_price CHECK (price >= 0),
    CONSTRAINT chk_tickets_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED'))
);

CREATE INDEX idx_tickets_uuid ON tickets(uuid);
CREATE INDEX idx_tickets_user_uuid ON tickets(user_uuid);
CREATE INDEX idx_tickets_schedule_uuid ON tickets(schedule_uuid);
CREATE INDEX idx_tickets_status ON tickets(status);
CREATE INDEX idx_tickets_booking_time ON tickets(booking_time);
CREATE INDEX idx_tickets_payment_id ON tickets(payment_id) WHERE payment_id IS NOT NULL;

-- Composite indexes for common queries
CREATE INDEX idx_tickets_user_status ON tickets(user_uuid, status, booking_time DESC);
CREATE INDEX idx_tickets_schedule_status ON tickets(schedule_uuid, status);
CREATE INDEX idx_tickets_pending_bookings ON tickets(booking_time) WHERE status = 'PENDING';
