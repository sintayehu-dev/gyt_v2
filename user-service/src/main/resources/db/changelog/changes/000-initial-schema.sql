CREATE TABLE user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    email VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_profiles PRIMARY KEY (id),
    CONSTRAINT uc_user_profiles_uuid UNIQUE (uuid),
    CONSTRAINT uc_user_profiles_email UNIQUE (email),
    CONSTRAINT chk_user_profiles_email_format CHECK (email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')
);

CREATE INDEX idx_user_profiles_email ON user_profiles(email);
CREATE INDEX idx_user_profiles_uuid ON user_profiles(uuid);
CREATE INDEX idx_user_profiles_created_at ON user_profiles(created_at DESC);

CREATE TABLE user_bookmarks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id BIGINT NOT NULL,
    schedule_uuid VARCHAR(36) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_bookmarks PRIMARY KEY (id),
    CONSTRAINT fk_user_bookmarks_user FOREIGN KEY (user_id) REFERENCES user_profiles (id) ON DELETE CASCADE,
    CONSTRAINT uc_user_bookmarks_user_schedule UNIQUE (user_id, schedule_uuid)
);

CREATE INDEX idx_user_bookmarks_user_id ON user_bookmarks(user_id);
CREATE INDEX idx_user_bookmarks_schedule_uuid ON user_bookmarks(schedule_uuid);

CREATE TABLE user_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid VARCHAR(36) NOT NULL,
    user_id BIGINT NOT NULL,
    movie_uuid VARCHAR(36) NOT NULL,
    rating INTEGER NOT NULL,
    review VARCHAR(500),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_ratings PRIMARY KEY (id),
    CONSTRAINT uc_user_ratings_uuid UNIQUE (uuid),
    CONSTRAINT fk_user_ratings_user FOREIGN KEY (user_id) REFERENCES user_profiles (id) ON DELETE CASCADE,
    CONSTRAINT uc_user_ratings_user_movie UNIQUE (user_id, movie_uuid),
    CONSTRAINT chk_user_ratings_rating CHECK (rating >= 1 AND rating <= 10)
);

CREATE INDEX idx_user_ratings_user_id ON user_ratings(user_id);
CREATE INDEX idx_user_ratings_movie_uuid ON user_ratings(movie_uuid);
CREATE INDEX idx_user_ratings_rating ON user_ratings(rating);
CREATE INDEX idx_user_ratings_created_at ON user_ratings(created_at);

-- Composite indexes for common queries
CREATE INDEX idx_user_ratings_movie_recent ON user_ratings(movie_uuid, created_at DESC);
CREATE INDEX idx_user_ratings_user_recent ON user_ratings(user_id, created_at DESC);
